#!/usr/bin/env python3
"""Build wokwi/sketch.ino: the firmware with VG_SIM=1 and every vg_*.h inlined into one file.

The Wokwi web editor is easiest to drive with a single sketch file, so this keeps
firmware/VibeGuard/ as the only source of truth.  Run:  python3 tools/build_wokwi.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "firmware" / "VibeGuard"
OUT = ROOT / "wokwi" / "sketch.ino"


def inline(path, seen):
    out = []
    for line in path.read_text().splitlines():
        m = re.match(r'\s*#include "(vg_\w+\.h)"', line)
        if m:
            name = m.group(1)
            if name not in seen:
                seen.add(name)
                out.append(f"// ===== {name} =====")
                out.extend(inline(SRC / name, seen))
            continue
        if line.strip() == "#pragma once":
            continue
        out.append(line)
    return out


def main():
    body = inline(SRC / "VibeGuard.ino", set())
    header = [
        "// GENERATED by tools/build_wokwi.py from firmware/VibeGuard/. Edit the firmware, not this file.",
        "#define VG_SIM 1",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(header + body) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
